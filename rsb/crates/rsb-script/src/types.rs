//! Generates `rsb.d.luau`, the typed module luau-lsp reads for
//! `require("@rsb")`, from `api` (functions and types),
//! `rsb_core::services` (service tables) and `rsb_core::css::PROPERTIES`
//! (the `Style` table) and `rsb_core::icons::ICON_NAMES` (`IconName`).
//! The committed copy at `crates/rsb-script/types/rsb.d.luau` must equal
//! `generate()`; a test checks it.
//!
//! In the config folder, `types/rsb.d.luau` is rewritten by `rsb types` and
//! at every start when it differs (so an upgrade never leaves stale types);
//! `.luaurc` and `.vscode/settings.json` are written only when missing,
//! because users edit them.
//!
//! Generated types flatten every `*Props` (no intersections) and turn each
//! `PROPERTIES` row into an optional `Style` field. Options whose default is
//! nil are typed `nil` in strict mode; the docs show the cast pattern
//! (`options = { city = (nil :: string?) }`).

use std::collections::BTreeMap;
use std::fmt::Write as _;

use rsb_core::css::PROPERTIES;
use rsb_core::icons::ICON_NAMES;
use rsb_core::services::{COMMON_FIELDS, SERVICE_ENUMS, SERVICE_SCHEMAS, SERVICE_TYPES};

use crate::api::{API_ITEMS, API_TYPES};

/// Where the committed copy lives, relative to this crate.
pub const COMMITTED: &str = "types/rsb.d.luau";

/// The whole file: a header comment, `export type` for every type, the
/// module type, and `return (nil :: any) :: Rsb`.
pub fn generate() -> String {
    let mut out = String::new();
    out.push_str("-- Generated by `rsb types`. Do not edit.\n");
    out.push_str("-- Types for require(\"@rsb\"): rsb.d.luau is read by luau-lsp, never run.\n\n");

    // Literal unions from the service schemas.
    for (name, values) in SERVICE_ENUMS {
        let union: Vec<String> = values.iter().map(|v| format!("\"{v}\"")).collect();
        let _ = writeln!(out, "export type {name} = {}\n", union.join(" | "));
    }

    let icons: Vec<String> = ICON_NAMES.iter().map(|n| format!("\"{n}\"")).collect();
    out.push_str("--- A named icon\n");
    let _ = writeln!(out, "export type IconName = {}\n", icons.join(" | "));

    out.push_str("--- Inline style: CSS properties with `_` for `-`; numbers are px for lengths\n");
    out.push_str("export type Style = {\n");
    for p in PROPERTIES {
        let ty = if p.values.contains("<length") || p.values.contains("<number") || p.values.contains("<percentage") {
            "(number | string)?"
        } else {
            "string?"
        };
        let _ = writeln!(out, "    {}: {ty}, -- {}", p.name.replace('-', "_"), p.values);
    }
    out.push_str("}\n\n");

    for t in API_TYPES {
        let _ = writeln!(out, "--- {}", t.doc);
        let _ = writeln!(out, "export type {}{} = {}\n", t.name, t.generics, t.def);
    }

    for t in SERVICE_TYPES {
        let _ = writeln!(out, "--- {}", t.doc);
        let _ = writeln!(out, "export type {} = {{", t.name);
        for f in t.fields {
            let _ = writeln!(out, "    --- {}", f.doc);
            let _ = writeln!(out, "    {}: {},", f.name, f.ty);
        }
        out.push_str("}\n\n");
    }

    for s in SERVICE_SCHEMAS {
        let _ = writeln!(out, "--- {}", s.doc);
        let _ = writeln!(
            out,
            "--- The values are nil until the first reading arrives (status \"starting\"): check before using one."
        );
        let _ = writeln!(out, "export type {} = {{", s.type_name);
        // Until the first reading a service holds only its status, so every value is optional.
        for (f, sampled_value) in s.fields.iter().map(|f| (f, true)).chain(COMMON_FIELDS.iter().map(|f| (f, false))) {
            let optional = if sampled_value && !f.ty.ends_with('?') { "?" } else { "" };
            let _ = writeln!(out, "    --- {}", f.doc);
            let _ = writeln!(out, "    {}: {}{optional},", f.name, f.ty);
        }
        if s.sampled {
            out.push_str("    --- sample every d (the fastest reader wins; calling again replaces your wish)\n");
            let _ = writeln!(out, "    interval: (self: {}, d: Duration) -> (),", s.type_name);
        }
        for c in s.commands {
            let _ = writeln!(out, "    --- {}", c.doc);
            let params = if c.params.is_empty() { String::new() } else { format!(", {}", c.params) };
            let _ = writeln!(out, "    {}: (self: {}{params}) -> (),", c.name, s.type_name);
        }
        out.push_str("}\n\n");
    }

    // The module: dotted paths become nested tables.
    let mut tree = Node::default();
    for item in API_ITEMS {
        tree.insert(item.path, item.ty, item.doc, item.yields);
    }
    out.push_str("export type Rsb = {\n");
    tree.write(&mut out, 1);
    out.push_str("}\n\nreturn (nil :: any) :: Rsb\n");
    out
}

#[derive(Default)]
struct Node {
    ty: Option<(&'static str, &'static str, bool)>,
    children: BTreeMap<&'static str, Node>,
    order: Vec<&'static str>,
}

impl Node {
    fn insert(&mut self, path: &'static str, ty: &'static str, doc: &'static str, yields: bool) {
        match path.split_once('.') {
            None => {
                self.order.push(path);
                self.children.entry(path).or_default().ty = Some((ty, doc, yields));
            }
            Some((head, rest)) => {
                if !self.children.contains_key(head) {
                    self.order.push(head);
                }
                self.children.entry(head).or_default().insert(rest, ty, doc, yields);
            }
        }
    }

    fn write(&self, out: &mut String, depth: usize) {
        let pad = "    ".repeat(depth);
        for name in &self.order {
            let node = &self.children[name];
            match node.ty {
                Some((ty, doc, yields)) => {
                    let note = if yields { " Waits for a result: call it inside a task." } else { "" };
                    let _ = writeln!(out, "{pad}--- {doc}.{note}", doc = doc.trim_end_matches('.'));
                    let _ = writeln!(out, "{pad}{name}: {ty},");
                }
                None => {
                    let _ = writeln!(out, "{pad}{name}: {{");
                    node.write(out, depth + 1);
                    let _ = writeln!(out, "{pad}}},");
                }
            }
        }
    }
}

/// `.luaurc` for the config folder: strict mode and the `@rsb` alias.
pub fn luaurc() -> &'static str {
    "{\n  \"languageMode\": \"strict\",\n  \"aliases\": {\n    \"rsb\": \"./types/rsb.d\"\n  }\n}\n"
}

/// `.vscode/settings.json` for the config folder (luau-lsp extension).
pub fn vscode_settings() -> &'static str {
    "{\n  \"luau-lsp.platform.type\": \"standard\",\n  \"luau-lsp.sourcemap.enabled\": false,\n  \"files.associations\": { \"*.luau\": \"luau\" }\n}\n"
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn every_api_path_is_in_the_output() {
        let text = generate();
        for item in API_ITEMS {
            let leaf = item.path.rsplit('.').next().unwrap();
            assert!(text.contains(&format!("{leaf}: ")), "{}", item.path);
        }
        assert!(text.contains("export type Style = {"));
        assert!(text.contains("font_size: (number | string)?"));
        assert!(text.contains("export type IconName = \"volume_mute\""));
        assert!(text.ends_with("return (nil :: any) :: Rsb\n"));
    }

    #[test]
    fn props_types_are_flat() {
        let text = generate();
        assert!(!text.contains("Props &"), "no intersections");
        for t in API_TYPES.iter().filter(|t| t.name.ends_with("Props")) {
            assert!(t.def.starts_with('{'), "{}", t.name);
        }
    }

    #[test]
    fn the_generated_file_is_valid_luau_syntax() {
        mlua::prelude::LuaCompiler::new().compile(generate()).expect("the type file parses");
    }

    #[test]
    fn config_helpers_are_valid_json() {
        for text in [luaurc(), vscode_settings()] {
            serde_json::from_str::<serde_json::Value>(text).expect("valid json");
        }
    }

    #[test]
    fn output_is_stable() {
        assert_eq!(generate(), generate());
    }
}
